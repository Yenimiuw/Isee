-- Isee database setup. Run once in the Supabase SQL editor (Dashboard > SQL Editor > New query).
-- Safe to re-run: it only creates what is missing.

create table if not exists public.profiles (
  id          uuid primary key references auth.users (id) on delete cascade,
  full_name   text not null,
  role        text not null check (role in ('student', 'educator')),
  created_at  timestamptz not null default now()
);

create table if not exists public.courses (
  id             uuid primary key default gen_random_uuid(),
  code           text not null unique,
  name           text not null,
  educator_id    uuid not null references public.profiles (id) on delete cascade,
  password_hash  text not null,
  created_at     timestamptz not null default now()
);

create table if not exists public.enrollments (
  course_id    uuid not null references public.courses (id) on delete cascade,
  student_id   uuid not null references public.profiles (id) on delete cascade,
  enrolled_at  timestamptz not null default now(),
  primary key (course_id, student_id)
);

create table if not exists public.meetings (
  id            uuid primary key default gen_random_uuid(),
  course_id     uuid not null references public.courses (id) on delete cascade,
  title         text not null,
  meet_code     text not null,
  meet_url      text not null,
  scheduled_at  timestamptz not null default now(),
  created_at    timestamptz not null default now()
);

-- One tracked session per student per meeting.
create table if not exists public.sessions (
  id                 uuid primary key default gen_random_uuid(),
  meeting_id         uuid not null references public.meetings (id) on delete cascade,
  student_id         uuid not null references public.profiles (id) on delete cascade,
  started_at         timestamptz not null default now(),
  ended_at           timestamptz,
  last_heartbeat_at  timestamptz,
  unique (meeting_id, student_id)
);

-- join / away (switched tab, hostname = destination) / site (tab-to-tab while away) / return / leave.
-- The id is generated by the client so a retried batch never creates duplicates.
create table if not exists public.activity_events (
  id           uuid primary key,
  session_id   uuid not null references public.sessions (id) on delete cascade,
  type         text not null check (type in ('join', 'away', 'site', 'return', 'leave')),
  hostname     text,
  client_ts    timestamptz not null,
  received_at  timestamptz not null default now()
);

create index if not exists idx_enrollments_student on public.enrollments (student_id);
create index if not exists idx_meetings_course     on public.meetings (course_id, scheduled_at desc);
create index if not exists idx_sessions_meeting    on public.sessions (meeting_id);
create index if not exists idx_events_session      on public.activity_events (session_id, client_ts);

-- Row Level Security: enabled with no policies, so the public (anon) API can read nothing.
-- Only the Isee backend, using the service-role key, can access these tables.
alter table public.profiles        enable row level security;
alter table public.courses         enable row level security;
alter table public.enrollments     enable row level security;
alter table public.meetings        enable row level security;
alter table public.sessions        enable row level security;
alter table public.activity_events enable row level security;
